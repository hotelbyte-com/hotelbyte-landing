// Generates the code-split views of src/data/dailyStories.ts, which stays the
// single source of truth (edit stories there, never in the output).
//
// Output (src/data/generated/, git-ignored, rebuilt by `prebuild` and `predev`):
//   dailyStoryKeys.ts    [date, slug] pairs: date-alias routes and slug/date lookup.
//   dailyStoryList.ts    listing fields of every story, newest first (/stories).
//   dailyStoryLatest.ts  the newest story's listing fields (homepage feature).
//   stories/<date>.json  one complete story per file; the story page loads only
//                        the file it renders, so bodies never reach the main
//                        bundle, the homepage chunk, or other pages.
//
// Run `npm run gen:daily-stories` after editing dailyStories.ts when using the
// dev server or running `tsc` directly; `npm run build` does it automatically.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = path.join(root, 'src', 'data', 'dailyStories.ts');
const outDir = path.join(root, 'src', 'data', 'generated');
const storiesDir = path.join(outDir, 'stories');

// dailyStories.ts has no imports, so a type-stripping transpile is enough to
// load the real data and the real getDailyStoriesArchive() ordering.
const transpiled = ts.transpileModule(fs.readFileSync(sourceFile, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ES2022 },
  fileName: sourceFile,
}).outputText;
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'hotelbyte-daily-story-data-'));
let source;
try {
  const moduleFile = path.join(scratch, 'dailyStories.mjs');
  fs.writeFileSync(moduleFile, transpiled);
  source = await import(pathToFileURL(moduleFile).href);
} finally {
  fs.rmSync(scratch, { recursive: true, force: true });
}

const { dailyStories, getDailyStoriesArchive } = source;
if (!Array.isArray(dailyStories) || dailyStories.length === 0) {
  throw new Error('src/data/dailyStories.ts exports no stories');
}
const seenDates = new Set();
const seenSlugs = new Set();
for (const story of dailyStories) {
  if (seenDates.has(story.date)) throw new Error(`duplicate story date: ${story.date}`);
  if (seenSlugs.has(story.slug)) throw new Error(`duplicate story slug: ${story.slug}`);
  seenDates.add(story.date);
  seenSlugs.add(story.slug);
}

const pick = (obj, keys) => Object.fromEntries(keys.map((key) => [key, obj[key]]));
const listItem = (story) => ({
  date: story.date,
  slug: story.slug,
  content: Object.fromEntries(
    ['zh', 'en'].map((locale) => [locale, pick(story.content[locale], ['title', 'mood', 'summary'])]),
  ),
  visual: pick(story.visual, ['src', 'alt']),
});

const header = '// Generated by scripts/generate-daily-story-data.mjs from src/data/dailyStories.ts. Do not edit.\n';
const files = new Map();
files.set(
  path.join(outDir, 'dailyStoryKeys.ts'),
  `${header}export const dailyStoryKeys: ReadonlyArray<readonly [date: string, slug: string]> = ${JSON.stringify(
    dailyStories.map((story) => [story.date, story.slug]),
  )};\n`,
);
const list = getDailyStoriesArchive().map(listItem);
files.set(
  path.join(outDir, 'dailyStoryList.ts'),
  `${header}import type { DailyStoryListItem } from '../dailyStoryTypes';\n\nexport const dailyStoryList: DailyStoryListItem[] = ${JSON.stringify(list, null, 2)};\n`,
);
files.set(
  path.join(outDir, 'dailyStoryLatest.ts'),
  `${header}import type { DailyStoryListItem } from '../dailyStoryTypes';\n\nexport const latestDailyStory: DailyStoryListItem = ${JSON.stringify(list[0], null, 2)};\n`,
);
for (const story of dailyStories) {
  files.set(path.join(storiesDir, `${story.date}.json`), `${JSON.stringify(story)}\n`);
}

// Write only what changed (keeps mtimes stable for the dev server) and drop
// stories that no longer exist.
fs.mkdirSync(storiesDir, { recursive: true });
let written = 0;
for (const [file, content] of files) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
  fs.writeFileSync(file, content);
  written += 1;
}
for (const name of fs.readdirSync(storiesDir)) {
  if (!files.has(path.join(storiesDir, name))) {
    fs.rmSync(path.join(storiesDir, name));
    written += 1;
  }
}
console.log(`daily story data: ${dailyStories.length} stories, ${written} file(s) updated`);
